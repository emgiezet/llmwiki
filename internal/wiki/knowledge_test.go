func TestSearchKnowledge_MatchesTopicTitleAndBody(t *testing.T) {
	root := t.TempDir()
	writeKnowledge(t, root, "global", "oidc-setup.md", "# Identity\n\nKeycloak realms per tenant.\n")
	writeKnowledge(t, root, "global", "billing.md", "# Billing\n\nStripe webhooks.\n")

	store := wiki.NewStore(root)
	layers := []string{"global"}

	for _, tc := range []struct{ name, query, wantTopic string }{
		{"matches topic", "oidc", "oidc-setup"},
		{"matches title", "identity", "oidc-setup"},
		{"matches body", "keycloak", "oidc-setup"},
		{"case insensitive", "STRIPE", "billing"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got, err := store.SearchKnowledge(layers, tc.query)
			require.NoError(t, err)
			require.Len(t, got, 1)
			assert.Equal(t, tc.wantTopic, got[0].Topic)
		})
	}

	got, err := store.SearchKnowledge(layers, "definitely-not-present")
	require.NoError(t, err)
	assert.Empty(t, got)
}

func TestSearchKnowledge_SkipsGitDirAndNonMarkdown(t *testing.T) {
	root := t.TempDir()
	writeKnowledge(t, root, "global", "auth.md", "# Auth\n")
	writeKnowledge(t, root, "global", "notes.txt", "not markdown")
	// A submodule checkout leaves a .git directory full of files inside the layer.
	gitDir := filepath.Join(root, wiki.KnowledgeDir, "global", ".git")
	require.NoError(t, os.MkdirAll(gitDir, 0755))
	require.NoError(t, os.WriteFile(filepath.Join(gitDir, "COMMIT_EDITMSG.md"), []byte("# nope\n"), 0644))

	got, err := wiki.NewStore(root).SearchKnowledge([]string{"global"}, "")
	require.NoError(t, err)
	require.Len(t, got, 1)
	assert.Equal(t, "auth", got[0].Topic)
}

