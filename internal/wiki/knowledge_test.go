func TestSearchKnowledge_RefusesSymlinkedEntry(t *testing.T) {
	root := t.TempDir()
	secret := filepath.Join(root, "secret.md")
	require.NoError(t, os.WriteFile(secret, []byte("# Secret\n"), 0644))
	layerDir := filepath.Join(root, wiki.KnowledgeDir, "global")
	require.NoError(t, os.MkdirAll(layerDir, 0755))
	if err := os.Symlink(secret, filepath.Join(layerDir, "leak.md")); err != nil {
		t.Skip("symlinks not supported:", err)
	}
	writeKnowledge(t, root, "global", "real.md", "# Real\n")

	got, err := wiki.NewStore(root).SearchKnowledge([]string{"global"}, "")
	require.NoError(t, err, "a symlink is skipped, not fatal")
	require.Len(t, got, 1)
	assert.Equal(t, "real", got[0].Topic)
}

