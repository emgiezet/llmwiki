// writeKnowledge drops a raw file into <root>/knowledge/<layer>/<name>.
func writeKnowledge(t *testing.T, root, layer, name, content string) {
	t.Helper()
	dir := filepath.Join(root, wiki.KnowledgeDir, layer)
	require.NoError(t, os.MkdirAll(dir, 0755))
	require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0644))
}

func TestSearchKnowledge_ReturnsLayersInCallerOrder(t *testing.T) {
	root := t.TempDir()
	writeKnowledge(t, root, "global", "auth.md", "# Auth Standard\n\nAll services use OIDC.\n")
	writeKnowledge(t, root, "platform-team", "deploy.md", "# Deploy\n\nArgoCD, one app per service.\n")

	store := wiki.NewStore(root)

	got, err := store.SearchKnowledge([]string{"platform-team", "global"}, "")
	require.NoError(t, err)
	require.Len(t, got, 2)
	assert.Equal(t, "platform-team", got[0].Layer, "caller's first layer must come first")
	assert.Equal(t, "global", got[1].Layer)

	// Reversing the caller's list reverses the results — order is priority.
	got, err = store.SearchKnowledge([]string{"global", "platform-team"}, "")
	require.NoError(t, err)
	require.Len(t, got, 2)
	assert.Equal(t, "global", got[0].Layer)
	assert.Equal(t, "platform-team", got[1].Layer)
}

