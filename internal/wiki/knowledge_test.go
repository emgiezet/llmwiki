func TestListKnowledgeLayers(t *testing.T) {
	root := t.TempDir()
	writeKnowledge(t, root, "platform-team", "deploy.md", "# Deploy\n")
	writeKnowledge(t, root, "global", "auth.md", "# Auth\n")
	// A stray file directly under knowledge/ is not a layer.
	require.NoError(t, os.WriteFile(filepath.Join(root, wiki.KnowledgeDir, "stray.md"), []byte("# Stray\n"), 0644))
	// Hidden/VCS directories are not layers either.
	require.NoError(t, os.MkdirAll(filepath.Join(root, wiki.KnowledgeDir, ".git"), 0755))

	got, err := wiki.NewStore(root).ListKnowledgeLayers()
	require.NoError(t, err)
	assert.Equal(t, []string{"global", "platform-team"}, got, "sorted, dirs only, no dotdirs")
}

