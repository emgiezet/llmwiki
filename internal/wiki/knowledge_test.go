func TestSearchKnowledge_HandDroppedFileWithoutFrontMatter(t *testing.T) {
	root := t.TempDir()
	writeKnowledge(t, root, "global", "adr-001.md", "# Use Postgres\n\nWe picked Postgres over Mongo.\n")

	got, err := wiki.NewStore(root).SearchKnowledge([]string{"global"}, "")
	require.NoError(t, err)
	require.Len(t, got, 1)
	assert.Equal(t, "adr-001", got[0].Topic)
	assert.Equal(t, "Use Postgres", got[0].Title, "title comes from the first H1")
	assert.Contains(t, got[0].Body, "We picked Postgres over Mongo.")
	assert.Equal(t, filepath.Join("knowledge", "global", "adr-001.md"), got[0].Path)
}

func TestSearchKnowledge_StripsFrontMatterFromBody(t *testing.T) {
	root := t.TempDir()
	writeKnowledge(t, root, "global", "ingested.md",
		"---\nname: ingested\ntype: knowledge\n---\n\n## Summary\n\nGenerated by ingest.\n")

	got, err := wiki.NewStore(root).SearchKnowledge([]string{"global"}, "")
	require.NoError(t, err)
	require.Len(t, got, 1)
	assert.NotContains(t, got[0].Body, "type: knowledge", "front matter must not leak into the body")
	assert.Contains(t, got[0].Body, "Generated by ingest.")
	assert.Equal(t, "ingested", got[0].Title, "no H1 — falls back to the topic")
}

